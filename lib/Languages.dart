  static String getString(BuildContext context, String key,
      {String? languageCode}) {
    String locale =
        languageCode ?? Localizations.localeOf(context).languageCode;
    switch (locale) {
      case 'en':
        return EN[key] ?? '';
      case 'gr':
        return GR[key] ?? '';
      case 'es':
        return ES[key] ?? '';
      case 'por':
        return POR[key] ?? '';
      case 'fr':
        return FR[key] ?? '';
      case 'de':
        return DE[key] ?? '';
      case 'ru':
        return RU[key] ?? '';
      case 'ja':
        return JA[key] ?? '';
      case 'ch':
        return CH[key] ?? '';
      default:
        return 'en';
    }
  }
